// Label layout, in pixels, with every font dot drawn 2 pixels wide: a character cell is
// 6 dots (5 plus a 1-dot gap), the box has a 1-dot margin on each side, and it is 9 dots tall
// (7 plus the margins). Written out as numbers so no two formulas can coincide.
const SCALE: u32 = 2;
const ADVANCE: u32 = 12;
const MARGIN: u32 = 2;
const SIDES: u32 = 4;
const HEIGHT: u32 = 18;
const BOX: [u8; 4] = [12, 12, 14, 255];
const INK: [u8; 4] = [236, 236, 236, 255];

/// The glyph for `c`, case-insensitive; `?` for anything the font lacks.
fn glyph(c: char) -> [u8; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map_or(GLYPHS[GLYPHS.len() - 1].1, |(_, rows)| *rows)
}

/// Burns `text` in light ink on a dark box whose top-left corner is at (`x`, `y`).
pub(crate) fn label(image: &mut Image, x: u32, y: u32, text: &str) {
    let chars = text.chars().count() as u32;
    image.fill_rect(x, y, SIDES + chars * ADVANCE, HEIGHT, BOX);
    for (i, c) in text.chars().enumerate() {
        let left = x + MARGIN + i as u32 * ADVANCE;
        for (row, bits) in glyph(c).iter().enumerate() {
            for col in 0..5 {
                if bits >> (4 - col) & 1 == 1 {
                    image.fill_rect(
                        left + col * SCALE,
                        y + MARGIN + row as u32 * SCALE,
                        SCALE,
                        SCALE,
                        INK,
                    );
                }
            }
        }
    }
}
